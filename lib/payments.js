export const getPayMethod = (slug) => PAY_METHODS.find((m) => m.slug === slug) || null;

export function providersByPayment(key) {
  return PROVIDERS.filter((p) => PAYMENTS[p.slug]?.[key] === true && plansOf(p.slug).length > 0)
    .map((p) => ({ ...p, minPrice: minPriceOf(p.slug) }))
    .sort((a, b) => (a.minPrice ?? 1e9) - (b.minPrice ?? 1e9));
}

export function paymentList(slug) {
  const pay = PAYMENTS[slug] || {};
  const out = [];
  if (pay.mir) out.push('карта МИР');
  if (pay.sbp) out.push('СБП');
  if (pay.crypto) out.push('криптовалюта');
  if (pay.card) out.push('Visa и Mastercard');
  if (pay.paypal) out.push('PayPal');
  return out;
}
